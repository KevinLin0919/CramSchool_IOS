    /// Mean P(cross) across the forest. 0 = certainly a circle, 1 = certainly
    /// a cross; the distance from 0.5 is what the caller turns into confidence.
    static func probabilityOfCross(_ features: [Double]) -> Double {
        guard !roots.isEmpty else { return 0.5 }
        var total = 0.0
        for root in roots {
            var node = Int(root)
            while feature[node] >= 0 {
                let value = features[Int(feature[node])]
                node = Int(value <= threshold[node] ? left[node] : right[node])
            }
            total += threshold[node]
        }
        return total / Double(roots.count)
    }
